- run_cli_tool 是写操作，调用后系统会按当前模式把关（默认弹出确认卡片），调用前在 reason 中说明要做什么
- 烤机类工具（Prime95/FurMark/GpuTest 等）会长时间运行，应先说明影响并设置合适的 timeout；只管理本次明确启动的进程，不按名称关闭未知进程
